-- 031. Кейсы: работы, которые были на самом деле.
--
-- Правило раздела, и оно не обсуждается: здесь только то, что делалось.
-- Ни одного придуманного клиента, ни одной придуманной цифры. Выдуманный
-- кейс рушится первым же вопросом «а можно телефон этого клиента»,
-- и рушит вместе с собой всё остальное на сайте.
--
-- Отсюда три решения по форме:
--
--   1. Клиенты не названы. Названия и города не выдумываются, а настоящие
--      без разрешения публиковать нельзя. Написано то, что следует из
--      самой задачи: если речь о колеровочном аппарате — это магазин
--      красок, и это не догадка.
--
--   2. Никаких «в восемь раз быстрее». Внутреннюю экономику считать надо,
--      но на витрине она читается как «значит, мне переплачивают».
--      Клиент покупает решённую беду, а не чужую производительность.
--
--   3. У каждого кейса есть раздел «что осталось за кадром» — то, что
--      не вошло или пошло не так. Кейс без единой шероховатости выглядит
--      как реклама; кейс с ней — как отчёт.

