-- 029. Цены: час 10 000 ₸ и абонементы чуть ниже рынка.
--
-- Откуда цифры. Смотрел открытые прайсы казахстанских франчайзи и студий
-- 1С 10 сентября 2026 года:
--
--   maximum1c.kz/plans   Базовый 60 000 ₸/мес — 5 ч, реакция 4 ч, сверх пакета 12 000 ₸/ч
--                        Стандарт 100 000 ₸/мес — 10 ч, реакция 2 ч, сверх 10 000 ₸/ч
--                        Максимум 135 000 ₸/мес — 15 ч, реакция 1 ч, сверх 9 000 ₸/ч
--                        Аудит базы 1С — 30 000–150 000 ₸
--   onsetpro.kz          «Базовый» от 25 000 ₸/мес — 4 часа работ
--   1cbit.kz             Аудит базы «1С:Бухгалтерия для Казахстана» — 47 792 ₸
--   gem.kz (01.07.2026)  услуги специалиста свыше тарифа 23 000–26 600 ₸/ч
--   dialogs.kz           консультант 24 500 ₸/ч
--   1c-rating.kz         26 390 / 31 610 / 35 960 ₸/ч по уровням специалистов
--   optimalcourse.kz     12 000 ₸/ч (план «Бизнес» и выше)
--   pos-tech.kz          6 000 ₸/ч разово, 4 000 ₸/ч от 10 часов, 3 500 ₸/ч от 30
--
-- Что из этого следует. Рынок расслоился: крупные франчайзи держат
-- 23 000–27 000 ₸/ч, небольшие студии 6 000–12 000 ₸/ч, а месячные пакеты
-- идут от 25 000 ₸ за 4 часа до 135 000 ₸ за 15.
--
-- Час назначен владельцем: 10 000 ₸. Это середина «студийного» слоя и вдвое
-- ниже крупных франчайзи — при том, что ответ обещан за час, а у них
-- 2–48 часов. Абонементы поставлены чуть ниже рынка и с эффективной
-- ставкой ниже разового часа: пакет должен быть выгоднее разовой работы,
-- иначе покупать его незачем.
--
--   Сопровождение   45 000 ₸/мес за 5 ч  (у maximum1c 60 000 за те же 5 ч)
--   Сопровождение+  85 000 ₸/мес за 10 ч (у maximum1c 100 000 за 10 ч)
--   Наблюдение      25 000 ₸/мес за 2 ч плюс ежедневная проверка обменов
--   Скорая          18 000 ₸ за обращение, час работ включён
--
-- Цены — данные, а не код: любая правится в панели, и проданные абонементы
-- от этого не меняются (условия копируются при продаже, миграция 021).
-- Поэтому здесь только первое заполнение: правка не перезапишет то, что
-- владелец поменяет руками — see `where price = 0` ниже.

-- ── 1. Ставка часа по умолчанию ─────────────────────────────────────────────
--
-- Ставка живёт у клиента: разным клиентам можно назначить разную. Но пока
-- у клиента её нет, счёт по часам считается по нулю — то есть выставляется
-- на ноль. Значение по умолчанию убирает эту дыру.

alter table crm.company alter column hourly_rate set default 10000;

update crm.company set hourly_rate = 10000
 where hourly_rate is null or hourly_rate = 0;

comment on column crm.company.hourly_rate is
  'Ставка часа для этого клиента, тенге. По умолчанию 10 000 — базовая ставка студии.';

-- ── 2. Тарифы ───────────────────────────────────────────────────────────────

do $$
declare r record;
begin
  for r in select id from core.tenant loop
    -- Правим только не заполненные цены: если владелец уже поставил свою,
    -- миграция не имеет права её переписать.
    update crm.plan set price = 18000, overage_rate = 12000, included_minutes = 60,
           note = 'Оплата за обращение: час работ включён, дальше по 12 000 ₸/ч. '
                  'Ответ в течение часа в рабочее время.'
     where tenant_id = r.id and code = 'incident' and price = 0;

    update crm.plan set price = 25000, overage_rate = 10000,
           note = 'Ежедневная проверка обменов плюс два часа работ в месяц. '
                  'Сверх пакета 10 000 ₸/ч.'
     where tenant_id = r.id and code = 'watch' and price = 0;

    update crm.plan set price = 45000, overage_rate = 10000,
           note = 'Пять часов работ в месяц и приоритет в очереди. '
                  'Сверх пакета 10 000 ₸/ч. Эффективная ставка 9 000 ₸/ч.'
     where tenant_id = r.id and code = 'support' and price = 0;

    -- Ставка для тех, кто без абонемента: перерасхода у них не бывает, но
    -- поле используется как ставка по умолчанию в расчётах.
    update crm.plan set overage_rate = 10000,
           note = 'Сроки для заявок от клиентов без абонемента. Час на первый ответ — '
                  'то, что обещает сайт. Работа по 10 000 ₸/ч.'
     where tenant_id = r.id and code = 'default' and coalesce(overage_rate, 0) = 0;

    -- Второй уровень сопровождения. Он есть у всех на рынке, и он же — то,
    -- куда клиент переходит, когда пяти часов перестаёт хватать. Без него
    -- разговор упирается в «давайте считать по часам», а это шаг назад.
    insert into crm.plan (tenant_id, code, title, kind, price, included_minutes,
                          overage_rate, react_minutes, resolve_minutes, clock, sort, note)
    values (r.id, 'support10', 'Сопровождение, 10 часов', 'subscription',
            85000, 600, 9000, 60, 1440, 'business', 40,
            'Десять часов работ в месяц. Сверх пакета 9 000 ₸/ч. '
            'Эффективная ставка 8 500 ₸/ч — тариф для тех, кому пяти часов мало.')
    on conflict (tenant_id, code) do nothing;
  end loop;
end $$;

