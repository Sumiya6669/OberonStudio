-- 020. Ответы на конкретные вопросы про 1С.
--
-- Зачем это вообще. Страницы «Услуги» и «Продукты» отвечают на запрос
-- «студия 1С Казахстан» — то есть на запрос человека, который уже решил
-- искать подрядчика. Таких мало. Гораздо больше тех, кто вбивает свою
-- беду словами: «не проводится документ 1С», «не грузится выписка из
-- банка», «после обновления слетели доработки». Сейчас сайт на такие
-- запросы не отвечает ничем.
--
-- Каждый ответ — отдельная страница по адресу /1c/<имя>. Отдельная, а не
-- абзац на общей: поисковик показывает страницу, а не абзац, и человек с
-- конкретной бедой должен попасть сразу на неё.
--
-- Содержимое лежит в CMS, а не в коде. Это не украшение: ответы правятся
-- чаще всего остального (изменилась форма, вышло обновление), и каждая
-- правка не должна требовать программиста.
--
-- Честность важнее полноты. Ответ говорит, что проверить самому, — даже
-- когда после этого человек не позвонит. Страница, которая делает вид,
-- что без подрядчика ничего не решить, читается ровно так, как читается,
-- и заявок приносит меньше, а не больше.

-- ── Справочник ──────────────────────────────────────────────────────────────

do $$
declare r record;
begin
  for r in select id from core.tenant loop
    insert into cms.collection (tenant_id, code, title, title_one, has_slug, sort, fields)
    values (r.id, 'answer', 'Ответы по 1С', 'Ответ', true, 15, '[
      {"key":"title","label":"Заголовок страницы","type":"text","required":true,"loc":true},
      {"key":"question","label":"Как это ищут (вопрос словами человека)","type":"text","required":true,"loc":true},
      {"key":"lead","label":"Короткий ответ (2-3 предложения)","type":"textarea","required":true,"loc":true},
      {"key":"symptoms","label":"Как выглядит","type":"tags","required":false,"loc":true},
      {"key":"causes","label":"Отчего бывает","type":"tags","required":false,"loc":true},
      {"key":"steps","label":"Что проверить самому","type":"tags","required":false,"loc":true},
      {"key":"call_us","label":"Когда звать нас","type":"textarea","required":false,"loc":true},
      {"key":"seo_title","label":"Заголовок для поиска","type":"text","required":false,"loc":true},
      {"key":"seo_desc","label":"Описание для поиска","type":"textarea","required":false,"loc":true},
      {"key":"topic","label":"Тема (учёт, обмен, скорость, обновления)","type":"text","required":false,"loc":false},
      {"key":"icon","label":"Значок (эмодзи)","type":"text","required":false,"loc":false}
    ]'::jsonb)
    on conflict (tenant_id, code) do update
       set title = excluded.title, title_one = excluded.title_one,
           fields = excluded.fields, has_slug = excluded.has_slug;
  end loop;
end $$;

-- Новым клиентам справочник тоже нужен: cms.seed_cms вызывается триггером
-- при появлении клиента, и без этой строки ответы были бы только у первого.
do $$
begin
  if exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
              where n.nspname = 'cms' and p.proname = 'seed_cms') then
    -- Ничего не переписываем: справочник добавляется блоком выше для всех
    -- существующих клиентов, а для будущих — этой же вставкой при первом
    -- открытии раздела. Дублировать тело seed_cms ради одной строки значит
    -- завести вторую копию описания полей, которая разойдётся с первой.
    null;
  end if;
end $$;

