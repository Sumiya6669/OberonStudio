-- 046. Почта, которой нет.
--
-- В настройках сайта с самого начала лежал адрес для писем: сначала
-- hello@oberon.studio (015, сид), потом hello@tinker.kz (035, переименование).
-- Ни один из этих ящиков не существует. Домен не куплен, почта не заведена,
-- MX-записи нет — письмо по такому адресу не попадает никуда и даже не
-- возвращается отправителю сколько-нибудь понятной ошибкой.
--
-- Чем это плохо. Адрес выводился как полноценный канал связи: плиткой в блоке
-- контактов и в разметке Organization, откуда его забирают поиск, карты и
-- агрегаторы. То есть сайт не просто хранил лишнюю строку — он публично
-- приглашал писать туда, откуда ответа не будет. Человек, выбравший почту
-- вместо Telegram (а её выбирают именно те, кому нужен «официальный» канал:
-- бухгалтерия, закуп, юрист), уходит молча и считает, что ему не ответили.
-- Это худший вид вымысла на сайте: он не приукрашивает, он теряет обращения.
--
-- Что делаем. Убираем ключ email из cms.settings у всех клиентов. Именно
-- удаляем ключ, а не записываем пустую строку: сайт склеивает настройки из
-- базы поверх зашитых в код и при склейке пропускает пустые значения — так
-- что пустая строка и отсутствие ключа для вёрстки равнозначны, но пустая
-- строка выглядит как «адрес забыли дописать» и однажды будет «дописана»
-- обратно. Отсутствие ключа читается однозначно: канала нет.
--
-- Заодно затыкаем источник. cms.seed (015) при заведении нового клиента
-- по-прежнему вписывает мёртвый адрес, а функция эта длинная и переписывать
-- её целиком ради одной строки — лишний риск. Поэтому правим триггерную
-- обёртку cms.g_seed: она в три строки, и после сида снимает ключ. Новый
-- клиент заводится уже без почты.
--
-- Обратно всё делается одной строкой: появится настоящий ящик — его вписывают
-- в панели «Сайт → Настройки», поле там осталось на месте. Пустое поле
-- честнее красивой выдумки, но только пока оно пустое, а не заполнено ложью.

-- ── 1. Убрать мёртвый адрес у всех клиентов ─────────────────────────────────

update cms.settings
   set data = data - 'email'
 where data ? 'email';

-- ── 2. Не заводить его заново новым клиентам ────────────────────────────────

create or replace function cms.g_seed() returns trigger
language plpgsql security definer set search_path = cms, public
as $$
begin
  perform cms.seed(new.id);
  -- cms.seed (015) всё ещё вписывает несуществующий ящик в настройки.
  -- Снимаем ключ сразу: канал связи, которого нет, не должен доживать
  -- до первой публикации сайта нового клиента.
  update cms.settings set data = data - 'email' where tenant_id = new.id;
  return new;
end $$;

-- ── 3. Проверка ─────────────────────────────────────────────────────────────

do $$
declare bad int;
begin
  select count(*) into bad from cms.settings where data ? 'email';
  if bad > 0 then
    raise exception 'в cms.settings осталась почта у % клиентов', bad;
  end if;
end $$;
