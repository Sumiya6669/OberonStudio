-- 041. Частичная оплата перестаёт ломать учёт.
--
-- Что было. Индекс entry_doc_idx запрещал две записи учёта с одинаковыми
-- (клиент, вид, документ). Задумывался он ради одного: чтобы триггер,
-- сработавший дважды, не создал второй черновик по тому же СЧЁТУ. Но под
-- его правило попали и записи вида payment_in, у которых doc_id — это тот
-- же счёт. В результате первая оплата по счёту проходила, а вторая падала
-- с ошибкой уникальности прямо в лицо тому, кто её вносил.
--
-- Почему это важно. Частичная оплата — не исключение, а обычный случай:
-- аванс и остаток, две недели между ними. Статус partly_paid в системе
-- предусмотрен, то есть половину пути база проходила и обрывалась на
-- второй оплате. Нашлось это учениями по деньгам, а не в бою, и хорошо.
--
-- Что делаем. У записи об оплате уже есть свой сторож — entry_payment_idx
-- по payment_id: одна запись на одну оплату, повторный вызов триггера
-- ничего не задвоит. Значит entry_doc_idx должен сторожить только те
-- записи, у которых источник — сам документ, а не оплата.

drop index if exists acc.entry_doc_idx;

create unique index entry_doc_idx on acc.entry (tenant_id, kind, doc_id)
  where doc_id is not null and payment_id is null and status <> 'void';

comment on index acc.entry_doc_idx is
  'Один черновик на документ. Записи об оплатах сюда не входят: их стережёт entry_payment_idx, иначе вторая оплата по счёту не пройдёт.';
