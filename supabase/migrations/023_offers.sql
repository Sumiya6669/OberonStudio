-- 023. Офферы: страницы под конкретную покупку.
--
-- Раздел «Услуги» отвечает на запрос «студия 1С Казахстан» — то есть
-- человеку, который уже решил искать подрядчика. Разборы в /1c отвечают
-- тому, у кого что-то сломалось. Между ними дыра: человек понял, что сам
-- не справится, и хочет знать, ЧТО именно он покупает, за сколько и что
-- будет дальше. «Обсудить проект» на этот вопрос не отвечает.
--
-- Оффер — это страница про одну покупку: что входит, что не входит,
-- как проходит, сколько стоит. Раздел «что не входит» здесь не
-- формальность: он снимает половину возражений и отсекает не тех
-- клиентов до разговора, а не после трёх встреч.
--
-- Цены НЕ проставлены. Их задаёт владелец: цифра, взятая мной с потолка,
-- на публичном сайте становится обещанием, за которое отвечает он.
-- Пустая цена показывается как «по запросу» — это правда, а не заглушка.

