function List({ items }) {
  return (
    <ul className="space-y-2 pl-5 list-disc marker:text-primary/60">
      {items.map((item, i) => <li key={i}>{item}</li>)}
    </ul>
  );
}

/** Таблица карточками: на телефоне пять колонок не читаются. */
function Cards({ rows, title, labels }) {
  return (
    <div className="grid gap-3">
      {rows.map((row, i) => (
        <div key={i} className="rounded-2xl border border-line bg-surface/60 p-4">
          <p className="text-sm font-semibold text-white/80 mb-2">{row[title]}</p>
          <dl className="grid gap-1.5 text-xs leading-relaxed">
            {Object.entries(labels).map(([key, label]) => (
              <div key={key} className="sm:grid sm:grid-cols-[130px_1fr] sm:gap-3">
                <dt className="text-white/30">{label}</dt>
                <dd className="text-white/60">{row[key]}</dd>
              </div>
            ))}
          </dl>
        </div>
      ))}
    </div>
  );
}

