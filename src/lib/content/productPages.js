/** Разборы /1c, в которых этот продукт назван решением (src/lib/content/answerProducts.js). */
export function relatedAnswerSlugs(id) {
  return Object.entries(ANSWER_PRODUCTS)
    .filter(([, row]) => row.product === id)
    .map(([slug]) => slug);
}

/** Разборы с заголовками: из базы, если она ответила, иначе — из запасного списка. */
export function relatedAnswers(id, answers) {
  return relatedAnswerSlugs(id)
    .map((slug) => {
      const fromDb = (answers || []).find((a) => a.slug === slug);
      const title = fromDb?.title || ANSWER_TITLES[slug];
      return title ? { slug, title } : null;
    })
    .filter(Boolean);
}

/** Статьи, где продукт указан в related.products. */
export function relatedArticles(id, articles) {
  return (articles || []).filter((a) => (a.related?.products || []).includes(id));
}

/** Расширения 1С, у которых есть страница, — в порядке каталога. */
export const PRODUCT_PAGE_IDS = PRODUCTS
  .filter((p) => p.group === '1c' && PRODUCT_PAGES[p.id])
  .map((p) => p.id);

/** Продукт каталога и его страница: { product, page } или null. */
export function getProductPage(id) {
  const product = PRODUCTS.find((p) => p.id === id && p.group === '1c');
  const page = PRODUCT_PAGES[id];
  return product && page ? { product, page } : null;
}
