/**
 * Авторы раздела «Статьи экспертов» (/stati).
 *
 * Один автор — одна запись. Ключ записи — то, что статья пишет в поле
 * `author`. Чтобы добавить автора, достаточно дописать запись сюда; см.
 * README-admin.md, раздел «Статьи экспертов».
 *
 * Правило раздела: только то, что автор подтвердил сам. Ни должностей
 * «на вырост», ни лет опыта, ни сертификатов, которых автор не назвал.
 * Нет фото — поле `photo` пустое, и на странице выводятся инициалы.
 *
 * Поля:
 *   name  — имя и фамилия, как автор хочет их видеть;
 *   role  — роль одной строкой;
 *   bio   — два-три предложения о себе: чем занимается, о чём пишет;
 *   photo — путь к фото в public/ (например '/authors/albert.jpg') или '';
 *   url   — страница автора, если есть (по умолчанию — /o-kompanii для своих).
 */

export const AUTHORS = {
  'albert-gaan': {
    name: 'Альберт Гаан',
    // Имя, роль и опыт подтверждены владельцем 09.10.2026.
    role: 'Ведущий разработчик 1С и ИИ, Tinker',
    bio: '6+ лет в 1С и ИИ. Разрабатывает расширения для 1С:Бухгалтерии для Казахстана 3.0 и Комплексной автоматизации 2.4, ИИ-агентов и интеграции с Kaspi и банками. Пишет о том, что проверяется в коде продуктов Tinker и в нормах, сверенных с источником.',
    photo: '',
    url: '/o-kompanii',
  },
};

/** Автор статьи или null, если ключ не найден (статья тогда подписана брендом). */
export function getAuthor(key) {
  return (key && AUTHORS[key]) || null;
}

/** Инициалы для круга без фото: «Альберт Гаан» → «АГ». */
export function initials(name) {
  return String(name || '')
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0].toUpperCase())
    .join('');
}
