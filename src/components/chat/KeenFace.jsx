/**
 * Лицо консультанта.
 *
 * До этого в шапке чата стояли буквы «AG» — остаток от прежнего имени,
 * который никто не читал как лицо. У консультанта должно быть своё: человек
 * пишет не «сайту», а кому-то.
 *
 * Смотреть на него будут в круге 32 пикселя, и это решило всё остальное.
 * Первый вариант держал по бокам скобы тисков, как в знаке студии, и
 * приподнятую бровь — «внимание». На большом размере получалось хорошо, а на
 * настоящем скобы превращались в квадратные скобки вокруг кляксы, бровь — в
 * случайную царапину, и вместе это читалось как грязь, а не как лицо.
 * Поэтому здесь осталось только то, что живёт в круге: голова, два глаза,
 * рот и точка-искра. Родство со знаком даёт не повтор скоб, а цвет и та же
 * скруглённая геометрия.
 */
export default function KeenFace({ size = 32, className = '' }) {
  return (
    <svg viewBox="0 0 48 48" width={size} height={size} fill="none"
         className={className} role="presentation" aria-hidden="true">
      {/* Искра: единственная мелочь, которая на 32 пикселях ещё видна,
          потому что это точка, а не штрих. */}
      <circle cx="24" cy="7.5" r="2.2" fill="currentColor" />
      <path d="M 24 9.5 L 24 12.5" stroke="currentColor" strokeWidth="2.6"
            strokeLinecap="round" opacity="0.65" />

      {/* Голова */}
      <rect x="9" y="12.5" width="30" height="28" rx="9.5"
            stroke="currentColor" strokeWidth="3.2" />

      <circle cx="18.5" cy="24" r="2.6" fill="currentColor" />
      <circle cx="29.5" cy="24" r="2.6" fill="currentColor" />

      <path d="M 19 32 L 29 32" stroke="currentColor" strokeWidth="2.8"
            strokeLinecap="round" />
    </svg>
  );
}
